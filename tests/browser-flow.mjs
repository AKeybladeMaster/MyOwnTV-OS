import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { ROOT, LOCAL, readJson } from '../tools/lib/files.mjs';

const started = Date.now();
const server = spawn(process.execPath, ['tools/preview.mjs'], { cwd: ROOT, env: { ...process.env, MYOWNTV_PREVIEW_PORT: '4174' }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
let startupTimer;
try {
  await Promise.race([once(server.stdout, 'data'), once(server, 'error').then(([error]) => { throw error; }), new Promise((_, reject) => { startupTimer = setTimeout(() => reject(new Error('Preview server did not start.')), 10000); })]);
  clearTimeout(startupTimer);
  const executablePath = process.env.MYOWNTV_BROWSER || (process.platform === 'win32' ? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' : undefined);
  browser = await chromium.launch({ executablePath, headless: true });
  const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, locale: 'en-GB', timezoneId: 'Europe/Rome' });
  const page = await context.newPage();
  const errors = []; const external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (new URL(request.url()).hostname !== '127.0.0.1') external.push(request.url()); });
  await page.addInitScript(() => { window.__launches = []; window.addEventListener('myowntv:preview-launch', event => window.__launches.push(event.detail.id)); });
  await page.goto('http://127.0.0.1:4174');
  await page.locator('.wallpaper.visible').waitFor();
  const focused = () => page.evaluate(() => document.activeElement.id);
  assert.equal(await focused(), 'dock-youtube.leanback.v4');
  await page.keyboard.press('ArrowRight');
  assert.equal(await focused(), 'dock-amazon');
  assert.equal(await page.locator('#focused-name').textContent(), 'Prime Video');
  await page.keyboard.press('ArrowUp');
  assert.equal(await focused(), 'screen-share');
  await page.keyboard.press('ArrowLeft'); await page.keyboard.press('ArrowLeft');
  assert.equal(await focused(), 'inputs');
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown');
  assert.equal(await page.locator('#library').getAttribute('aria-hidden'), 'false');
  assert.equal(await page.locator('#app-grid .app-tile').count(), (await readJson(path.join(ROOT, 'config/apps.json'))).length);
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => window.__launches.length === 1);
  assert.deepEqual(await page.evaluate(() => window.__launches), ['youtube.leanback.v4']);
  await page.keyboard.press('Escape');
  assert.equal(await focused(), 'dock-youtube.leanback.v4');
  await page.locator('#settings').click();
  assert.equal(await page.locator('#panel').getAttribute('aria-hidden'), 'false');
  await page.locator('#rotation').click();
  assert.equal(await page.locator('#rotation').textContent(), 'Every 30 minutes');
  await page.locator('#motion').click();
  assert.equal(await page.locator('#motion').textContent(), 'On');
  await page.locator('#edit-dock').click();
  await page.locator('[id="right-youtube.leanback.v4"]').click();
  await page.locator('#close-panel').click();
  assert.equal(await page.locator('#dock .app-tile').first().getAttribute('aria-label'), 'Prime Video');
  await page.reload();
  await page.locator('.wallpaper.visible').waitFor();
  assert.equal(await focused(), 'dock-amazon');
  assert.equal(await page.locator('#dock .app-tile').first().getAttribute('aria-label'), 'Prime Video');
  await page.locator('#settings').click();
  assert.equal(await page.locator('#rotation').textContent(), 'Every 30 minutes');
  assert.equal(await page.locator('#motion').textContent(), 'On');
  await page.locator('#close-panel').click();
  await page.setViewportSize({ width: 1280, height: 720 });
  const stage = await page.locator('#stage').boundingBox();
  assert.equal(Math.round(stage.width), 1280); assert.equal(Math.round(stage.height), 720);
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.evaluate(() => { localStorage.clear(); location.reload(); });
  await page.locator('.wallpaper.visible').waitFor();
  await page.locator('[id="dock-youtube.leanback.v4"]').focus();
  await fs.mkdir(path.join(LOCAL, 'qa'), { recursive: true });
  await page.screenshot({ path: path.join(LOCAL, 'qa/browser-home.png') });
  await page.keyboard.press('ArrowDown');
  await page.screenshot({ path: path.join(LOCAL, 'qa/browser-library.png') });
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  console.log('Browser flow passed: D-pad, launch adapter, library, dock reorder, persisted settings, reduced motion, 720p scaling, no external requests or page errors.');
  console.log('Desktop browser verification only; elapsed ' + (Date.now() - started) + ' ms.');
} finally {
  clearTimeout(startupTimer);
  if (browser) await browser.close();
  server.kill();
}
